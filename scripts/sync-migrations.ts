/**
 * Compiles `drizzle/*.sql` into `worker/migrations.generated.ts`.
 *
 * The database object applies its own schema migrations on start-up, so the
 * SQL has to travel inside the Worker bundle. Drizzle still owns the files:
 * `npm run db:generate` writes them, and this turns them into a module in
 * journal order. `--check` fails instead of writing, which is how the test
 * suite catches a migration that was generated but never compiled in.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const drizzleDir = path.join(root, 'drizzle')
export const outputPath = path.join(root, 'worker', 'migrations.generated.ts')

interface Journal {
  entries: { idx: number; tag: string }[]
}

/** Drizzle separates statements with this marker; SQLite takes them one at a time. */
const BREAKPOINT = '--> statement-breakpoint'

export function renderMigrations(): string {
  const journal = JSON.parse(
    readFileSync(path.join(drizzleDir, 'meta', '_journal.json'), 'utf8'),
  ) as Journal

  const migrations = [...journal.entries]
    .sort((a, b) => a.idx - b.idx)
    .map((entry) => ({
      // Versions start at 1 so that 0 can mean "nothing applied yet".
      version: entry.idx + 1,
      name: entry.tag,
      statements: readFileSync(path.join(drizzleDir, `${entry.tag}.sql`), 'utf8')
        .split(BREAKPOINT)
        .map((statement) => statement.trim())
        .filter((statement) => statement.length > 0),
    }))

  return [
    '// Generated by scripts/sync-migrations.ts from drizzle/*.sql. Do not edit.',
    '// Run `npm run db:sync` after `npm run db:generate`.',
    '',
    'export interface Migration {',
    '  version: number',
    '  name: string',
    '  statements: string[]',
    '}',
    '',
    `export const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)}`,
    '',
  ].join('\n')
}

const invokedDirectly = process.argv[1] === fileURLToPath(import.meta.url)

if (invokedDirectly) {
  const rendered = renderMigrations()
  if (process.argv.includes('--check')) {
    const current = readFileSync(outputPath, 'utf8')
    if (current !== rendered) {
      console.error('worker/migrations.generated.ts is out of date. Run `npm run db:sync`.')
      process.exitCode = 1
    } else {
      process.stdout.write('worker/migrations.generated.ts matches drizzle/.\n')
    }
  } else {
    writeFileSync(outputPath, rendered)
    process.stdout.write('wrote worker/migrations.generated.ts\n')
  }
}
