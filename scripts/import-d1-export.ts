/**
 * One-time: turns a `wrangler d1 export` dump into a script that loads the same
 * rows into the database object.
 *
 *   npx wrangler d1 export not-cal-hacks --remote --output export.sql
 *   tsx scripts/import-d1-export.ts export.sql import.sql
 *   npm run db:exec -- --remote --file import.sql
 *
 * The output replaces the contents of every application table with the dump,
 * and `db:exec` runs a file as one transaction, so the import is all or
 * nothing and running it twice leaves exactly the same rows as running it
 * once. That also makes it destructive after cutover: it would discard
 * anything written to the object since the dump was taken.
 *
 * Only row data crosses over. The schema is the object's own, built from the
 * same migrations, and D1's bookkeeping table stays behind.
 */
import { readFileSync, writeFileSync } from 'node:fs'

/** Children before parents, so the wipe never trips a foreign key. */
const TABLES = ['status_events', 'reviews', 'sessions', 'applications', 'rate_limits', 'users']

/** Tables whose AUTOINCREMENT counter has to carry over with the rows. */
const SEQUENCES = ['status_events']

/**
 * Splits a dump into statements on the semicolons that end them, ignoring any
 * inside string literals, quoted identifiers and comments.
 */
export function splitStatements(sql: string): string[] {
  const statements: string[] = []
  let start = 0
  let i = 0
  while (i < sql.length) {
    const ch = sql[i]!
    if (ch === "'" || ch === '"' || ch === '`') {
      // A doubled quote inside a literal is an escape, not the end of it.
      i++
      while (i < sql.length) {
        if (sql[i] === ch) {
          if (sql[i + 1] === ch) i++
          else break
        }
        i++
      }
    } else if (ch === '-' && sql[i + 1] === '-') {
      while (i < sql.length && sql[i] !== '\n') i++
    } else if (ch === '/' && sql[i + 1] === '*') {
      i = sql.indexOf('*/', i + 2)
      if (i === -1) i = sql.length
      else i++
    } else if (ch === ';') {
      const statement = sql.slice(start, i + 1).trim()
      if (statement.length > 1) statements.push(statement)
      start = i + 1
    }
    i++
  }
  const rest = sql.slice(start).trim()
  if (rest.length > 0) statements.push(rest)
  return statements
}

export function buildImport(dump: string): { sql: string; counts: Record<string, number> } {
  const statements = splitStatements(dump)
  const counts: Record<string, number> = Object.fromEntries(TABLES.map((t) => [t, 0]))
  const inserts: string[] = []
  const sequences: string[] = []

  for (const statement of statements) {
    const match = /^INSERT INTO "([^"]+)"/.exec(statement)
    if (!match) continue
    const table = match[1]!
    if (table in counts) {
      counts[table]!++
      inserts.push(statement)
    } else if (table === 'sqlite_sequence') {
      if (SEQUENCES.some((name) => statement.includes(`VALUES('${name}',`))) {
        sequences.push(statement)
      }
    }
  }

  const sql = [
    '-- Generated by scripts/import-d1-export.ts. Replaces every application row.',
    // Rows arrive in dump order, not dependency order; check keys at commit.
    'PRAGMA defer_foreign_keys = on;',
    ...TABLES.map((table) => `DELETE FROM "${table}";`),
    ...inserts,
    ...SEQUENCES.map((name) => `DELETE FROM sqlite_sequence WHERE name = '${name}';`),
    ...sequences,
    '',
  ].join('\n')

  return { sql, counts }
}

const [input, output] = process.argv.slice(2)
if (input && output) {
  const { sql, counts } = buildImport(readFileSync(input, 'utf8'))
  writeFileSync(output, sql)
  console.log(`wrote ${output}`)
  for (const [table, n] of Object.entries(counts)) console.log(`  ${table}: ${n}`)
} else if (process.argv[1]?.endsWith('import-d1-export.ts')) {
  console.error('usage: tsx scripts/import-d1-export.ts <export.sql> <import.sql>')
  process.exitCode = 1
}
